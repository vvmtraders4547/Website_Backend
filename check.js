async function checkId(id) {
  return new Promise((resolve) => {
    https.request('https://images.unsplash.com/photo-' + id + '?auto=format&w=10', { method: 'HEAD' }, (res) => {
      resolve({ id, status: res.statusCode });
    }).on('error', () => resolve({ id, status: 0 })).end();
  });
}

